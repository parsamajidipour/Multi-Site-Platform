export const projectContentByLocale = { fa, tr, ar };

export function applyProjectLocale(project, locale) {
  if (!locale || locale === "en") return project;
  const patch = projectContentByLocale[locale]?.[project.slug || project.id];
  if (!patch) return project;
  return {
    ...project,
    title: patch.title ?? project.title,
    description: patch.description ?? project.description,
    text: patch.text ?? project.text,
    status: patch.status ?? project.status,
    location: patch.location ?? project.location,
    projectType: patch.projectType ?? project.projectType,
    developmentType: patch.developmentType ?? project.developmentType,
    market: patch.market ?? project.market,
    overview: patch.overview ?? project.overview,
    scope: patch.scope ?? project.scope,
    highlights: patch.highlights ?? project.highlights,
  };
}

export function applyProjectsLocale(projects, locale) {
  return projects.map((project) => applyProjectLocale(project, locale));
}

